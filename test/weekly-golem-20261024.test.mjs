import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {weeklyInsignia,weeklyInsigniaFromId} from '../src/neon/weekly-boss-insignias.js'
const games=readFileSync(new URL('../src/neon/games.js',import.meta.url),'utf8')
const relics=readFileSync(new URL('../src/neon/relics.js',import.meta.url),'utf8')
test('weekly insignias are unique per Friday and champion/guardian',()=>{
 const champ=weeklyInsignia('2026-10-30',true)
 const guest=weeklyInsignia('2026-10-30',false)
 const next=weeklyInsignia('2026-11-06',true)
 assert.notEqual(champ.id,guest.id)
 assert.notEqual(champ.id,next.id)
 assert.notEqual(champ.name,next.name)
 assert.match(champ.name,/30\/10\/2026/)
 assert.match(next.name,/06\/11\/2026/)
 assert.deepEqual(weeklyInsigniaFromId(champ.id),champ)
 assert.deepEqual(weeklyInsigniaFromId(guest.id),guest)
 assert.equal(weeklyInsigniaFromId('insignia_semanal_20269999_campeao'),null)
 assert.equal(weeklyInsigniaFromId('insignia_tita_ancestral'),null)
})
test('powers are comparable to legacy badges and do not affect PvP',()=>{
 const champ=weeklyInsignia('2026-10-30',true)
 const guest=weeklyInsignia('2026-10-30',false)
 assert.equal(champ.boss,.03)
 assert.equal(champ.raidAttack,.03)
 assert.equal(champ.bossCrit,.01)
 assert.equal(champ.raidCrit,.01)
 assert.equal(guest.boss,.01)
 assert.equal(guest.raidAttack,.01)
 assert.equal(guest.bossCrit,0)
 assert.match(champ.effect,/sem PvP/)
 assert.match(guest.effect,/sem PvP/)
 assert.match(relics,/const relic=RELICS\[itemId\]\|\|weeklyInsigniaFromId\(itemId\)/)
 assert.match(relics,/SELECT item_id FROM player_active_relics WHERE jid=\$1/)
 assert.match(relics,/item_id LIKE 'insignia_semanal_%'/)
})
test('weekly rewards, HP, ATK and no duplicate recurring badges',()=>{
 assert.match(games,/8000000\+Math\.floor\(Math\.random\(\)\*1500001\)/)
 assert.match(games,/maxHp,atk:200,participants/)
 assert.match(games,/cash:1000000,xp:12000,epicBoxes:15/)
 assert.match(games,/cash:750000,xp:9000,epicBoxes:12/)
 assert.match(games,/cash:525000,xp:6500,epicBoxes:9/)
 assert.match(games,/cash:350000,xp:4500,epicBoxes:7/)
 assert.match(games,/cash:225000,xp:3000,epicBoxes:5/)
 assert.match(games,/const upgradedWeeklyEdition=key=>String\(key\|\|\x27\x27\)>=\x272026-10-30\x27/)
 assert.match(games,/weeklyInsignia\(s.weekendKey,position===1\)/)
 assert.match(games,/ON CONFLICT\(jid,item_id\) DO UPDATE\s+SET quantity=GREATEST\(inventories\.quantity,1\)/)
 assert.match(games,/position<=5\?tier:null/)
 assert.match(games,/Number\(p.damage\|\|0\)>?=\(upgradedWeeklyEdition\(s.weekendKey\)\?10000:1\)/)
})
